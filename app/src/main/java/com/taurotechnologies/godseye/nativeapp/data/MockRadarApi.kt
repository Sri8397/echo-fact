package com.taurotechnologies.godseye.nativeapp.data

/** Available signal layers in the native layered radar. */
@kotlinx.serialization.Serializable
enum class RadarLayer(val label: String) {
    SEISMIC("Seismic"),
    WEATHER("Weather"),
    MARITIME("Maritime"),
    FLIGHTS("Flights"),
    HAZARDS("Hazards"),
    OUTAGES("Outages"),
    UNREST("Unrest"),
    MILITARY("Military"),
    NUCLEAR("Nuclear"),
    CONFLICTS("Conflicts"),
    CYBER("Cyber"),
    FIRES("Fires"),
    DATACENTERS("Datacenters"),
    SATELLITES("Satellites"),
    WEBCAMS("Webcams"),
    DISEASE("Disease"),
    DISPLACEMENT("Displacement"),
    SANCTIONS("Sanctions"),
    FUEL("Fuel"),
    PIPELINES("Pipelines"),
    MINERALS("Minerals"),
}

/** A fictional, static signal used to prototype native radar presentation. */
@kotlinx.serialization.Serializable
data class RadarSignal(
    val id: String,
    val layer: RadarLayer,
    val title: String,
    val locationName: String,
    val lat: Double,
    val lng: Double,
    val observedAt: String,
    val severity: String,
    val summary: String,
    val flight: FlightObservation? = null,
    val satellite: SatelliteObservation? = null,
    val provider: String? = null,
    val coverage: String? = null,
    val isSimulated: Boolean = true,
    val eventSourceUrl: String? = null,
    val magnitude: Double? = null,
    /** Map ranking for signals without an earthquake magnitude; higher shows first when markers are capped. */
    val rank: Double? = null,
)

